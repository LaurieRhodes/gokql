// gen.js — generates pkg/parser/result_names_gen.go from Kusto.Language:
// the result-name kind (and prefix) of every scalar and aggregate
// function, which decides the generated column name of an unnamed
// expression (strlen(s) → strlen_s, tostring(x) → x, sum(x) → sum_x).
//
// Usage: node gen.js <dir containing bridge.js and Kusto.Language.Bridge.js> > result_names_gen.go
// (npm @kusto/language-service-next, package/ directory)
const fs = require('fs');
const dir = process.argv[2];
global.window = global;
eval(fs.readFileSync(dir + '/bridge.js', 'utf8'));
eval(fs.readFileSync(dir + '/Kusto.Language.Bridge.js', 'utf8'));
const K = Kusto.Language;
const RK = K.Symbols.ResultNameKind;
const kinds = {};
for (const k in RK) if (typeof RK[k] === 'number') kinds[RK[k]] = k;
const lines = [];
const seen = {};
function add(list, agg) {
  for (const f of list) {
    const kind = kinds[f.ResultNameKind];
    if (kind === 'Default' || kind === undefined) continue;
    const key = (agg ? 'a:' : 's:') + f.Name;
    if (seen[key]) continue;
    seen[key] = 1;
    lines.push(`\t${JSON.stringify(f.Name)}: {Result${kind}, ${JSON.stringify(f.ResultNamePrefix || '')}},`);
  }
}
const out = [];
out.push('// Code generated by tools/gen-result-names/gen.js from Kusto.Language; DO NOT EDIT.');
out.push('');
out.push('package parser');
out.push('');
out.push('// scalarResultNames: functions whose unnamed calls are not named ColumnN.');
out.push('var scalarResultNames = map[string]resultName{');
lines.length = 0; add(K.Functions.All, false); out.push(...lines.sort());
out.push('}');
out.push('');
out.push('// aggregateResultNames: the same for aggregate functions.');
out.push('var aggregateResultNames = map[string]resultName{');
lines.length = 0; add(K.Aggregates.All, true); out.push(...lines.sort());
out.push('}');
console.log(out.join('\n'));
