package main

// embed_setup.go -- operational commands for the embedding extension.
//
// These are CLI FLAGS, not KQL commands, on purpose. gokql's
// non-Microsoft surface is exactly three commands (embed_text,
// .embed-into, .chunk-file) and that boundary is worth defending.
// "Is my backend healthy" and "how do I install one" are operational
// questions, not questions about data, so they do not belong in the
// query language.
//
// -embed-setup WRITES a script. It does not run one. gokql is a query
// engine; downloading a 17 MB binary and a 271 MB model and starting a
// long-lived server process are not things it should do behind a
// user's back, and a tool that fetches and executes remote binaries is
// a much harder thing to get approved on a client's machine than one
// that prints a script you can read first.

import (
	"context"
	"fmt"
	"os"
	"runtime"
	"strings"
	"time"

	"github.com/LaurieRhodes/gokql/pkg/embed"
	"github.com/LaurieRhodes/gokql/pkg/engine"
)

// runEmbedCheck probes the configured backend and reports. Exit code
// is non-zero on failure so it can gate a CI step or a deploy.
func runEmbedCheck() int {
	eng := engine.New(nil)
	em := engine.ResolveEmbedderForDiagnostics(eng)

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()

	report := embed.Diagnose(ctx, em)
	fmt.Print(report.String())
	if !report.OK() {
		fmt.Fprintln(os.Stderr, "\nembedding backend is NOT ready")
		return 1
	}
	fmt.Println("\nembedding backend is ready")
	return 0
}

// runEmbedSetup writes a setup script and explains what it does. It
// deliberately stops short of running it.
func runEmbedSetup(path string) int {
	if runtime.GOOS != "linux" && runtime.GOOS != "darwin" {
		fmt.Fprintf(os.Stderr,
			"-embed-setup generates a POSIX shell script; on %s run it under WSL, "+
				"or install Ollama and use GOKQL_EMBED=ollama\n", runtime.GOOS)
		return 1
	}
	if path == "" {
		path = "setup-embeddings.sh"
	}
	if _, err := os.Stat(path); err == nil {
		fmt.Fprintf(os.Stderr, "%s already exists; refusing to overwrite\n", path)
		return 1
	}
	if err := os.WriteFile(path, []byte(setupScript), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "writing %s: %v\n", path, err)
		return 1
	}

	// Render the run command as the user would type it: a bare
	// filename needs "./", an explicit path must not get one.
	runAs := path
	if !strings.ContainsAny(path, "/\\") {
		runAs = "./" + path
	}

	fmt.Printf(`Wrote %s

It downloads, into ~/.gokql/:
  - llama-server, ~17 MB, from the official ggml-org/llama.cpp GitHub release
  - nomic-embed-text-v1.5.f16.gguf, ~271 MB, from nomic-ai on Hugging Face
and starts a local server on 127.0.0.1:8080.

Read it before running it. Then:

  %s
  export GOKQL_EMBED="openai:nomic-embed-text-v1.5@http://127.0.0.1:8080/v1/embeddings"
  gokql -embed-check

Nothing is downloaded or executed by gokql itself.
`, path, runAs)
	return 0
}

const setupScript = `#!/usr/bin/env bash
# Local embedding backend for gokql. Generated by: gokql -embed-setup
#
# Downloads a llama.cpp server binary and a GGUF embedding model into
# ~/.gokql, then starts the server on 127.0.0.1:8080.
#
# Pin both versions. An unpinned model is a silent change of vector
# space: re-embedding against a different build can produce vectors
# that store and rank without error and mean something else.
set -euo pipefail

LLAMA_BUILD="${LLAMA_BUILD:-b11223}"
MODEL_REPO="${MODEL_REPO:-nomic-ai/nomic-embed-text-v1.5-GGUF}"
MODEL_FILE="${MODEL_FILE:-nomic-embed-text-v1.5.f16.gguf}"
PORT="${PORT:-8080}"

# --pooling MUST be explicit. Unspecified means the server uses
# whatever the GGUF's converter baked in, and a wrong value returns
# vectors of the correct shape with the wrong meaning. nomic and e5
# are mean-pooled; bge is cls.
POOLING="${POOLING:-mean}"

# --ubatch-size is the PHYSICAL batch size and must be at least your
# largest chunk in tokens. At the default 512, a 1612-token input
# fails with "too large to process". .chunk-file's 1500-char default
# is roughly 375 tokens, but headroom is cheap.
CTX="${CTX:-2048}"

HOME_DIR="${GOKQL_EMBED_HOME:-$HOME/.gokql}"
BIN_DIR="$HOME_DIR/llama-$LLAMA_BUILD"
MODEL_PATH="$HOME_DIR/$MODEL_FILE"
mkdir -p "$HOME_DIR"

if [ ! -x "$BIN_DIR/llama-server" ]; then
  echo "==> downloading llama.cpp $LLAMA_BUILD (~17 MB)"
  url="https://github.com/ggml-org/llama.cpp/releases/download/$LLAMA_BUILD/llama-$LLAMA_BUILD-bin-ubuntu-x64.tar.gz"
  tmp="$(mktemp -d)"
  curl -fSL --retry 3 -o "$tmp/llama.tar.gz" "$url"
  echo "    sha256: $(sha256sum "$tmp/llama.tar.gz" | cut -d' ' -f1)"
  mkdir -p "$BIN_DIR"
  tar xzf "$tmp/llama.tar.gz" -C "$BIN_DIR" --strip-components=1
  rm -rf "$tmp"
  chmod +x "$BIN_DIR/llama-server"
else
  echo "==> llama-server $LLAMA_BUILD already present"
fi

# ALWAYS run the resumable download, even when the file exists.
# "the file is there" is not "the file is complete": an interrupted
# download leaves a truncated GGUF whose first four bytes still spell
# GGUF, so a skip-if-exists guard plus a magic-byte check will happily
# serve a truncated model. curl -C - is a no-op when the file is
# already complete, so this costs one HEAD-equivalent round trip.
MODEL_URL="https://huggingface.co/$MODEL_REPO/resolve/main/$MODEL_FILE"
echo "==> fetching $MODEL_FILE (~271 MB, resumable; no-op if already complete)"
curl -fSL --retry 3 -C - -o "$MODEL_PATH" "$MODEL_URL" || {
  # curl exits 33 when the server cannot resume but the local file is
  # already whole; treat a size match as success rather than failing.
  [ -f "$MODEL_PATH" ] || exit 1
}

# Verify completeness against the advertised length, not against the
# file merely existing.
REMOTE_BYTES="$(curl -sIL "$MODEL_URL" | awk 'BEGIN{IGNORECASE=1} /^content-length:/ {v=$2} END {gsub(/\r/,"",v); print v}')"
LOCAL_BYTES="$(stat -c%s "$MODEL_PATH" 2>/dev/null || stat -f%z "$MODEL_PATH")"
if [ -n "$REMOTE_BYTES" ] && [ "$LOCAL_BYTES" -lt "$REMOTE_BYTES" ]; then
  echo "ERROR: $MODEL_PATH is truncated ($LOCAL_BYTES of $REMOTE_BYTES bytes)." >&2
  echo "       Re-run this script to resume, or delete the file and start over." >&2
  exit 1
fi
if [ "$(head -c 4 "$MODEL_PATH")" != "GGUF" ]; then
  echo "ERROR: $MODEL_PATH is not a GGUF file (an HTML error page?)" >&2
  exit 1
fi
echo "    sha256: $(sha256sum "$MODEL_PATH" | cut -d' ' -f1)"

if curl -sf -m 2 "http://127.0.0.1:$PORT/health" >/dev/null 2>&1; then
  echo "==> something is already serving on 127.0.0.1:$PORT; not starting a second one"
  exit 0
fi

echo "==> starting llama-server on 127.0.0.1:$PORT (pooling=$POOLING, ctx=$CTX)"
LD_LIBRARY_PATH="$BIN_DIR" nohup "$BIN_DIR/llama-server" \
  -m "$MODEL_PATH" \
  --embeddings --pooling "$POOLING" \
  -c "$CTX" --ubatch-size "$CTX" --batch-size "$CTX" \
  --host 127.0.0.1 --port "$PORT" \
  > "$HOME_DIR/llama-server.log" 2>&1 &

for _ in $(seq 1 60); do
  if curl -sf -m 2 "http://127.0.0.1:$PORT/health" >/dev/null 2>&1; then
    echo "==> ready"
    echo
    echo "   export GOKQL_EMBED=\"openai:nomic-embed-text-v1.5@http://127.0.0.1:$PORT/v1/embeddings\""
    echo "   gokql -embed-check"
    echo
    echo "   log:  $HOME_DIR/llama-server.log"
    echo "   stop: pkill -f llama-server"
    exit 0
  fi
  sleep 1
done

echo "ERROR: server did not become healthy; see $HOME_DIR/llama-server.log" >&2
exit 1
`
